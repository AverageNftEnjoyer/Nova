#!/usr/bin/env node
// Second half of `npm run build:agent-core` (after `tsc -p tsconfig.json`).
//
// tsc compiles src/**/*.ts into dist/ but does not copy the plain-JS modules those files import
// (for example src/db/index.js, src/db/paths.js, src/security/secrets/index.js). Their relative
// imports therefore point at files that do not exist under dist/.
//
// For every such import this writes a one-line re-export shim at the missing dist/ path:
//   export * from "../../src/db/index.js";
// A re-export (not a copy) keeps ONE module instance per file, so singletons such as the shared
// SQLite connection in src/db stay shared between the JS runtime and the compiled TS modules.
// The relative path also holds in the packaged layout, where src/ and dist/ are staged side by side
// (hud/scripts/prepare-runtime-resources.mjs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const distRoot = path.join(repoRoot, "dist");
const srcRoot = path.join(repoRoot, "src");
const RELATIVE_IMPORT = /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)["'](\.{1,2}\/[^"']+)["']/g;

function listJsFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listJsFiles(full));
    else if (entry.isFile() && entry.name.endsWith(".js")) out.push(full);
  }
  return out;
}

function toImportSpecifier(fromDir, target) {
  const rel = path.relative(fromDir, target).split(path.sep).join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

function main() {
  if (!fs.existsSync(distRoot)) {
    console.error(`[link-src-js-modules] ${distRoot} not found; run tsc first.`);
    process.exit(1);
  }
  const shims = new Map();
  const unresolved = new Set();
  for (const file of listJsFiles(distRoot)) {
    const source = fs.readFileSync(file, "utf8");
    for (const match of source.matchAll(RELATIVE_IMPORT)) {
      const target = path.resolve(path.dirname(file), match[1]);
      if (fs.existsSync(target) || shims.has(target)) continue;
      const relToDist = path.relative(distRoot, target);
      if (relToDist.startsWith("..")) continue;
      const srcCounterpart = path.join(srcRoot, relToDist);
      if (srcCounterpart.endsWith(".js") && fs.existsSync(srcCounterpart)) {
        shims.set(target, srcCounterpart);
      } else {
        unresolved.add(`${path.relative(repoRoot, file)} -> ${match[1]}`);
      }
    }
  }

  for (const [shimPath, srcFile] of shims) {
    fs.mkdirSync(path.dirname(shimPath), { recursive: true });
    const specifier = toImportSpecifier(path.dirname(shimPath), srcFile);
    fs.writeFileSync(
      shimPath,
      `// Generated by scripts/build/link-src-js-modules.mjs: re-exports the plain-JS source module.\nexport * from ${JSON.stringify(specifier)};\n`,
    );
  }
  console.log(`[link-src-js-modules] wrote ${shims.size} shim(s) under dist/.`);
  if (unresolved.size > 0) {
    console.error(`[link-src-js-modules] unresolved relative imports in dist/:\n  ${[...unresolved].join("\n  ")}`);
    process.exit(1);
  }
}

main();
